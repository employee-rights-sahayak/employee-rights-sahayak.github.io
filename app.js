  // same ranking as the server's /api/lawyers/nearby (haversine km, nearest 10) for the server-less GitHub Pages copy
  function nearest(lawyers, lat, lng) {
    const r = x => x * Math.PI / 180;
    const km = (a, b) => 6371 * 2 * Math.asin(Math.sqrt(Math.sin(r(b.lat - a.lat) / 2) ** 2 +
      Math.cos(r(a.lat)) * Math.cos(r(b.lat)) * Math.sin(r(b.lng - a.lng) / 2) ** 2));
    return lawyers.map(l => ({ ...l, distanceKm: Math.round(km({ lat, lng }, l) * 10) / 10 }))
      .sort((a, b) => a.distanceKm - b.distanceKm).slice(0, 10);
  }
